"""SQL view exposing account.analytic.line with the shape MIS Builder expects from a
move lines source (account_id, company_id, date, debit, credit, parent_state and a
one-account analytic_distribution).

Why: MIS Builder's analytic filter on account.move.line keeps the FULL balance of any
line that merely contains the analytic account in its distribution. Analytic lines are
already prorated (one line per account, with the distributed amount), so a report whose
move_lines_source is this model gives exact figures per analytic account/project, and it
also sees costs that never hit the general ledger as separate lines (timesheets and
manual analytic entries).

Sign convention follows account.move.line: analytic amount > 0 (revenue) becomes credit,
amount < 0 (cost) becomes debit, so ``balance = debit - credit = -amount`` and the usual
``-balp[...]`` expressions for income keep working.
"""

from psycopg2 import sql

from odoo import fields, models, tools


class MisAnalyticMoveLine(models.Model):
    _name = "mis.analytic.move.line"
    _description = "Analytic line as MIS move line"
    _inherit = ["analytic.mixin"]
    _auto = False
    _order = "date desc, id desc"

    name = fields.Char(readonly=True)
    date = fields.Date(readonly=True)
    company_id = fields.Many2one("res.company", readonly=True)
    company_currency_id = fields.Many2one(
        "res.currency", related="company_id.currency_id", readonly=True
    )
    account_id = fields.Many2one(
        "account.account", string="Financial Account", readonly=True
    )
    analytic_account_id = fields.Many2one("account.analytic.account", readonly=True)
    plan_id = fields.Many2one("account.analytic.plan", readonly=True)
    partner_id = fields.Many2one("res.partner", readonly=True)
    product_id = fields.Many2one("product.product", readonly=True)
    category = fields.Selection(
        selection=lambda self: (
            self.env["account.analytic.line"]._fields["category"].selection
        ),
        readonly=True,
    )
    line_origin = fields.Selection(
        selection=[
            ("journal", "Journal Item"),
            ("timesheet", "Timesheet"),
            ("manual", "Manual Analytic Entry"),
        ],
        readonly=True,
        help="Journal Item: analytic line generated by a posted journal item "
        "(invoices, bills, entries). Timesheet: line linked to a project "
        "(hr_timesheet). Manual: any other analytic line.",
    )
    is_timesheet = fields.Boolean(readonly=True)
    move_line_id = fields.Many2one("account.move.line", readonly=True)
    analytic_line_id = fields.Many2one("account.analytic.line", readonly=True)
    parent_state = fields.Selection(
        [("draft", "Draft"), ("posted", "Posted"), ("cancel", "Cancelled")],
        readonly=True,
    )
    unit_amount = fields.Float(string="Quantity", readonly=True)
    debit = fields.Monetary(currency_field="company_currency_id", readonly=True)
    credit = fields.Monetary(currency_field="company_currency_id", readonly=True)
    balance = fields.Monetary(currency_field="company_currency_id", readonly=True)
    amount = fields.Monetary(
        string="Analytic Amount", currency_field="company_currency_id", readonly=True
    )

    def _timesheet_sql(self):
        """Timesheets are analytic lines with a project (hr_timesheet). The column only
        exists when hr_timesheet is installed, so build the expression defensively."""
        self.env.cr.execute(
            """
            SELECT 1 FROM information_schema.columns
            WHERE table_name = 'account_analytic_line' AND column_name = 'project_id'
            """
        )
        if self.env.cr.fetchone():
            return "aal.project_id IS NOT NULL"
        return "FALSE"

    def init(self):
        cr = self.env.cr
        tools.drop_view_if_exists(cr, self._table)
        # In 16.0 models are initialized one by one (_auto_init + init), and this view
        # may come before res.company: create the column read by the view up front
        # (res.company's _auto_init then only adds the foreign key).
        if not tools.column_exists(
            cr, "res_company", "mis_analytic_fallback_account_id"
        ):
            tools.create_column(
                cr, "res_company", "mis_analytic_fallback_account_id", "int4"
            )
        # Lines without a general account (timesheets, manual entries) fall back to
        # the company's configured account or, when not set, to its first
        # "Cost of Revenue" account, so they still show up in a P&L.
        query = sql.SQL(
            """
            CREATE OR REPLACE VIEW {table} AS (
                SELECT
                    aal.id AS id,
                    aal.name AS name,
                    aal.date AS date,
                    aal.company_id AS company_id,
                    COALESCE(
                        aal.general_account_id,
                        rc.mis_analytic_fallback_account_id,
                        (
                            SELECT a.id
                            FROM account_account a
                            WHERE a.company_id = aal.company_id
                              AND a.account_type = 'expense_direct_cost'
                            ORDER BY a.code, a.id
                            LIMIT 1
                        )
                    ) AS account_id,
                    aal.account_id AS analytic_account_id,
                    aal.plan_id AS plan_id,
                    aal.partner_id AS partner_id,
                    aal.product_id AS product_id,
                    aal.category AS category,
                    CASE
                        WHEN aal.move_line_id IS NOT NULL THEN 'journal'
                        WHEN {timesheet} THEN 'timesheet'
                        ELSE 'manual'
                    END AS line_origin,
                    ({timesheet}) AS is_timesheet,
                    aal.move_line_id AS move_line_id,
                    aal.id AS analytic_line_id,
                    COALESCE(am.state, 'posted') AS parent_state,
                    aal.unit_amount AS unit_amount,
                    CASE WHEN aal.amount < 0 THEN -aal.amount ELSE 0 END AS debit,
                    CASE WHEN aal.amount > 0 THEN aal.amount ELSE 0 END AS credit,
                    -aal.amount AS balance,
                    aal.amount AS amount,
                    jsonb_build_object(aal.account_id::text, 100)
                        AS analytic_distribution
                FROM account_analytic_line aal
                JOIN res_company rc ON rc.id = aal.company_id
                LEFT JOIN account_move_line aml ON aml.id = aal.move_line_id
                LEFT JOIN account_move am ON am.id = aml.move_id
                WHERE aal.account_id IS NOT NULL
            )
            """
        ).format(
            table=sql.Identifier(self._table),
            # constant expression chosen by _timesheet_sql(), never user input
            timesheet=sql.SQL(self._timesheet_sql()),
        )
        cr.execute(query)
